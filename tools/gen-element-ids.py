#!/usr/bin/env python3
"""Generates the element id constants (PT_*) for C++ and Slang from TPT's own element list
(third_party/tpt/src/simulation/elements/meson.build), so ids always match the vendored TPT.

Run from the repository root after updating third_party/tpt:  tools/gen-element-ids.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
meson = (root / 'third_party/tpt/src/simulation/elements/meson.build').read_text()
block = meson[meson.index('simulation_elem_names'):]
block = block[block.index('[') + 1:block.index(']')]
# Each entry is a quoted name or disabler(), a removed element whose id stays reserved.
names = []
for entry in re.findall(r"'([A-Z0-9]+)'|(disabler\(\))", block):
    names.append(entry[0] or None)
assert names[0] == 'NONE', names[:3]

header = '// Generated by tools/gen-element-ids.py from TPT\'s element list. Do not edit.\n'
cpp = [header, '#pragma once', '', 'namespace bp {', '', 'enum ElementId : int {']
cpp += [f'    PT_{n} = {i},' for i, n in enumerate(names) if n]
cpp += [f'    PT_COUNT = {len(names)},', '};', '']
cpp += ['// The names above by id, to check them against the TPT build ("" for removed ids).',
        'inline constexpr const char *kElementIdNames[PT_COUNT] = {']
cpp += [f'    "{n or ""}",' for n in names]
cpp += ['};', '', '} // namespace bp', '']
(root / 'src/sim/ElementIds.h').write_text('\n'.join(cpp))

slang = [header, '#pragma once', '']
slang += [f'static const uint PT_{n} = {i};' for i, n in enumerate(names) if n]
slang += [f'static const uint PT_COUNT = {len(names)};', '']
(root / 'shaders/element_ids.slang').write_text('\n'.join(slang))
print(f'{len(names)} elements')
